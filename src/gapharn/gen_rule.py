"""Stage 2 (G1): rule-based harness generation for libarchive, driven by the API model.

Instead of one tiny harness per gap function, we emit a few *parametrized* harnesses
whose fuzz bytes choose among the library's format/filter/option functions. One
harness therefore exercises many API combinations, which is where real bugs live
(e.g. a specific writer format + unusual entry metadata + data). This follows
OGHarn's function classification (initializer / data-entry / processor) and
PromptFuzz's "turn constants into fuzzed variables".

The set of format/filter selector functions is discovered from api.json, not
hard-coded, so the harnesses automatically target the exact gap functions present
in the pinned libarchive version.

Usage:
    python -m gapharn.gen_rule libarchive            # -> harnesses/libarchive/*.c + manifest.json
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

SRC_ROOT = Path(__file__).resolve().parent.parent
TEMPLATES = SRC_ROOT / "templates"


# --------------------------------------------------------------- API queries

def _one_archive_arg(f: dict) -> bool:
    """True if the only parameter is a `struct archive *` (not archive_entry)."""
    ps = f["params"]
    if len(ps) != 1 or ps[0]["pointer_depth"] != 1:
        return False
    c = ps[0]["canonical"]
    return "archive" in c and "archive_entry" not in c


def selectors(functions: list[dict], prefix: str) -> list[str]:
    """Nullary selector functions (archive* only) whose name starts with prefix."""
    return sorted(f["name"] for f in functions if f["name"].startswith(prefix) and _one_archive_arg(f))


def has(functions: set[str], name: str) -> bool:
    return name in functions


def entry_str_setters(functions: list[dict], gap: set[str]) -> list[str]:
    """Gap archive_entry setters with signature (entry, const char *)."""
    out = []
    for f in functions:
        if not (f["name"].startswith("archive_entry_set_") or f["name"].startswith("archive_entry_copy_")):
            continue
        if f["name"] not in gap:
            continue
        ps = f["params"]
        if len(ps) == 2 and ps[1]["pointer_depth"] == 1 and ps[1]["canonical"].rstrip(" *").endswith("char"):
            if "wchar" not in ps[1]["canonical"]:  # skip wide-char (Windows) setters
                out.append(f["name"])
    return sorted(out)


# --------------------------------------------------------------- C emission

def _switch(var: str, calls: list[str], arg: str = "a") -> str:
    if not calls:
        return "    (void)0;"
    lines = [f"    switch ({var} % {len(calls)}) {{"]
    for i, fn in enumerate(calls):
        lines.append(f"    case {i}: {fn}({arg}); break;")
    lines.append("    }")
    return "\n".join(lines)


HEADER = """\
/* GapHarn G1 (generated by gapharn.gen_rule) - DO NOT EDIT BY HAND.
 * Library: {lib}   Recipe: {recipe}
 * Targets {ntarget} gap functions (see harnesses/{lib}/manifest.json).
 *
 * Build/run is handled by scripts/fuzz.sh; for a one-off:
 *   clang -g -O1 -fsanitize=address,undefined,fuzzer -I<build>/include -I templates \\
 *       {name}.c <build>/lib/{slib} $(cat <build>/LINK_FLAGS) -o {name}
 */
#include "gapharn_fuzz.h"
#include <archive.h>
#include <archive_entry.h>
#include <locale.h>
#include <signal.h>

int LLVMFuzzerInitialize(int *argc, char ***argv) {{
    (void)argc; (void)argv;
    /* Some filters/writers spawn external helper programs over a pipe; a broken
     * pipe would kill the fuzzer with SIGPIPE (exit 141), which is not a library bug. */
    signal(SIGPIPE, SIG_IGN);
    /* libarchive requires a UTF-8 locale for *_utf8 entry setters (maintainers'
     * guidance in libarchive#2233 / #587). Without it, the known crash from #2233
     * fires on almost every input and hides everything else. */
    setlocale(LC_ALL, "C.UTF-8");
    return 0;
}}
"""

# Filters implemented by shelling out to an external program (fork/exec + pipe).
# Excluded from the write harness: they test the subprocess plumbing, not the
# library, and depend on tools that may not be installed.
EXTERNAL_FILTERS = {
    "archive_write_add_filter_grzip", "archive_write_add_filter_lrzip",
    "archive_write_add_filter_lzop", "archive_write_add_filter_program",
}


def recipe_write(lib: str, funcs: list[dict], names: set[str], gap: set[str]) -> tuple[str, list[str]]:
    fmt_sel = selectors(funcs, "archive_write_set_format_")
    flt_sel = [f for f in selectors(funcs, "archive_write_add_filter_") if f not in EXTERNAL_FILTERS]
    zip_sel = selectors(funcs, "archive_write_zip_set_compression_")
    entry_set = ["archive_entry_set_uname", "archive_entry_set_gname",
                 "archive_entry_set_hardlink", "archive_entry_set_symlink"]
    entry_set = [e for e in entry_set if has(names, e)]

    targets = [f for f in (fmt_sel + flt_sel + zip_sel) if f in gap]
    for extra in ("archive_write_set_options", "archive_write_set_format_by_name",
                  "archive_write_add_filter_by_name", "archive_write_open_memory",
                  "archive_write_data", "archive_write_header"):
        if extra in gap:
            targets.append(extra)

    body = f"""
{HEADER.format(lib=lib, recipe="write", ntarget="many", name="harness_write", slib="libarchive.a")}
int LLVMFuzzerTestOneInput(const uint8_t *data, size_t size) {{
    GFuzz f; gf_init(&f, data, size);
    struct archive *a = archive_write_new();
    if (!a) return 0;

    /* [processor] choose one write format (gap functions) */
    uint8_t fmt = gf_u8(&f);
{_switch("fmt", fmt_sel)}

    /* [processor] choose one filter (gap functions) */
    uint8_t flt = gf_u8(&f);
{_switch("flt", flt_sel)}

    /* [processor] for zip, optionally choose a compression method (gap functions) */
    if (gf_u8(&f) & 1) {{ uint8_t z = gf_u8(&f);
{_switch("z", zip_sel)}
    }}

    /* Low compression level keeps 7zip/xz/lzma writers covered but fast enough
     * under ASan (default levels allocate large dictionaries and time out). */
    archive_write_set_options(a, "compression-level=1");

    /* [processor] option parser fed a fuzzed string (gap: archive_write_set_options) */
    char opt[64]; archive_write_set_options(a, gf_str(&f, opt, 48));

    /* [data-entry] in-memory sink; never touches the filesystem */
    static char out[1 << 20]; size_t used = 0;
    if (archive_write_open_memory(a, out, sizeof out, &used) != ARCHIVE_OK) {{
        archive_write_free(a); return 0;
    }}

    /* [processor] write a few entries with fuzzed metadata, then data */
    unsigned entries = 1u + gf_pick(&f, 4);
    for (unsigned i = 0; i < entries && gf_remaining(&f); i++) {{
        struct archive_entry *e = archive_entry_new();
        if (!e) break;
        char nm[129]; archive_entry_set_pathname(e, gf_str(&f, nm, 96));
        archive_entry_set_filetype(e, (gf_u8(&f) & 1) ? AE_IFREG : AE_IFDIR);
        archive_entry_set_perm(e, (int)(gf_u32(&f) & 07777));
        /* Take a bounded payload and declare EXACTLY its length. The API contract
         * is that write_data supplies `size` bytes; declaring more makes the
         * writers pad the difference on close (a 64-bit size means effectively
         * unbounded compression work, which starves the fuzzer). */
        size_t dlen; const uint8_t *d = gf_take(&f, (size_t)(gf_u32(&f) % 4096u), &dlen);
        archive_entry_set_size(e, (la_int64_t)dlen);
        archive_entry_set_mtime(e, (time_t)gf_i64(&f), (long)gf_u32(&f));
        archive_entry_set_uid(e, gf_i64(&f));
        archive_entry_set_gid(e, gf_i64(&f));
"""
    for setter in entry_set:
        body += f"        {{ char s[65]; {setter}(e, gf_str(&f, s, 48)); }}\n"
    body += """\
        if (archive_write_header(a, e) == ARCHIVE_OK && dlen)
            archive_write_data(a, d, dlen);
        archive_entry_free(e);
    }
    archive_write_close(a);
    archive_write_free(a);
    return 0;
}
"""
    return body, sorted(set(targets))


def recipe_read(lib: str, funcs: list[dict], names: set[str], gap: set[str]) -> tuple[str, list[str]]:
    targets = [n for n in (
        "archive_read_set_options", "archive_read_set_format_option", "archive_read_set_filter_option",
        "archive_read_set_option", "archive_read_append_filter", "archive_read_support_filter_by_code",
        "archive_read_support_format_by_code", "archive_read_set_format", "archive_read_open_memory",
        "archive_read_next_header2", "archive_read_header_position", "archive_seek_data",
    ) if n in gap]

    body = f"""
{HEADER.format(lib=lib, recipe="read", ntarget="many", name="harness_read", slib="libarchive.a")}
int LLVMFuzzerTestOneInput(const uint8_t *data, size_t size) {{
    GFuzz f; gf_init(&f, data, size);
    struct archive *a = archive_read_new();
    if (!a) return 0;

    /* [processor] enable all formats+filters, then fuzz extra selectors (gap functions) */
    archive_read_support_filter_all(a);
    archive_read_support_format_all(a);
    archive_read_support_format_by_code(a, (int)gf_u32(&f));
    archive_read_support_filter_by_code(a, (int)gf_u32(&f));
    if (gf_u8(&f) & 1) archive_read_append_filter(a, (int)gf_u32(&f));

    /* [processor] option parsers fed fuzzed strings (gap: *_set_option/options) */
    char m[24], o[24], v[24];
    archive_read_set_option(a, gf_str(&f, m, 16), gf_str(&f, o, 16), gf_str(&f, v, 16));
    char opts[64]; archive_read_set_options(a, gf_str(&f, opts, 48));

    /* [data-entry] rest of the input is the archive bytes */
    size_t alen; const uint8_t *abytes = gf_rest(&f, &alen);
    /* Empty buffers are skipped: the size-0 case is already recorded as a
     * triage candidate (division by zero in memory_read_skip). */
    if (alen == 0) {{ archive_read_free(a); return 0; }}
    if (archive_read_open_memory(a, (void *)abytes, alen) != ARCHIVE_OK) {{
        archive_read_free(a); return 0;
    }}

    /* [processor] walk entries and pull their data (bounded) */
    struct archive_entry *e;
    int guard = 0;
    while (archive_read_next_header(a, &e) == ARCHIVE_OK && guard++ < 4096) {{
        (void)archive_read_header_position(a);
        char buf[4096]; la_ssize_t r;
        int inner = 0;
        while ((r = archive_read_data(a, buf, sizeof buf)) > 0 && inner++ < 4096) {{ }}
        if (r < 0) break;
    }}
    archive_read_free(a);
    return 0;
}}
"""
    return body, sorted(set(targets))


def recipe_entry(lib: str, funcs: list[dict], names: set[str], gap: set[str]) -> tuple[str, list[str]]:
    str_setters = entry_str_setters(funcs, gap)
    getters = [g for g in (
        "archive_entry_strmode", "archive_entry_birthtime", "archive_entry_rdevmajor",
        "archive_entry_rdevminor", "archive_entry_filetype_is_set", "archive_entry_stat",
    ) if has(names, g)]
    targets = sorted(set(str_setters + getters +
                         [g for g in ("archive_entry_set_ino64", "archive_entry_set_pathname_utf8") if g in gap]))

    calls = ""
    for i, s in enumerate(str_setters):
        calls += f"    {{ char v[65]; {s}(e, gf_str(&f, v, 40)); }}\n"
    gets = ""
    for g in getters:
        if g == "archive_entry_stat":
            gets += "    { const struct stat *st = archive_entry_stat(e); (void)st; }\n"
        elif g == "archive_entry_strmode":
            gets += "    { const char *sm = archive_entry_strmode(e); (void)sm; }\n"
        else:
            gets += f"    {{ volatile long _ = (long){g}(e); (void)_; }}\n"

    body = f"""
{HEADER.format(lib=lib, recipe="entry", ntarget="many", name="harness_entry", slib="libarchive.a")}
#include <sys/stat.h>
#include <time.h>

/* Define GAPHARN_ROUNDTRIP_ASSERT at compile time to turn the pax round-trip
 * into a logic oracle (abort on a pathname/size mismatch). Off by default to
 * avoid false positives from formats that legitimately transform metadata. */
int LLVMFuzzerTestOneInput(const uint8_t *data, size_t size) {{
    GFuzz f; gf_init(&f, data, size);
    struct archive_entry *e = archive_entry_new();
    if (!e) return 0;

    char path[129]; archive_entry_set_pathname(e, gf_str(&f, path, 96));
    archive_entry_set_size(e, gf_i64(&f));
    archive_entry_set_filetype(e, AE_IFREG);
    archive_entry_set_perm(e, (int)(gf_u32(&f) & 07777));
    archive_entry_set_ino64(e, gf_i64(&f));
    archive_entry_set_dev(e, (dev_t)gf_u32(&f));
    archive_entry_set_rdev(e, (dev_t)gf_u32(&f));
    archive_entry_set_nlink(e, gf_u32(&f));
{calls}
    /* [getters] exercise read-side accessors on the fuzzed entry (gap functions) */
{gets}
    /* [data-entry] round-trip through the pax writer and reader */
    static char out[1 << 20]; size_t used = 0;
    struct archive *w = archive_write_new();
    archive_write_set_format_pax(w);
    if (archive_write_open_memory(w, out, sizeof out, &used) == ARCHIVE_OK) {{
        if (archive_write_header(w, e) == ARCHIVE_OK) {{
            struct archive *r = archive_read_new();
            archive_read_support_format_all(r);
            if (archive_read_open_memory(r, out, used) == ARCHIVE_OK) {{
                struct archive_entry *re;
                if (archive_read_next_header(r, &re) == ARCHIVE_OK) {{
#ifdef GAPHARN_ROUNDTRIP_ASSERT
                    const char *p0 = archive_entry_pathname(e), *p1 = archive_entry_pathname(re);
                    if (p0 && p1 && strcmp(p0, p1) != 0) __builtin_trap();
                    if (archive_entry_size(e) != archive_entry_size(re)) __builtin_trap();
#endif
                }}
            }}
            archive_read_free(r);
        }}
    }}
    archive_write_free(w);
    archive_entry_free(e);
    return 0;
}}
"""
    return body, targets


RECIPES = {"write": recipe_write, "read": recipe_read, "entry": recipe_entry}


def generate(lib: str, api_path: Path, gap_path: Path, out_dir: Path) -> dict:
    funcs = json.loads(api_path.read_text())["functions"]
    names = {f["name"] for f in funcs}
    gap = {g["name"] for g in json.loads(gap_path.read_text())["gap"]}

    out_dir.mkdir(parents=True, exist_ok=True)
    manifest = {"library": lib, "harnesses": {}}
    covered: set[str] = set()
    for recipe, fn in RECIPES.items():
        source, targets = fn(lib, funcs, names, gap)
        name = f"harness_{recipe}"
        (out_dir / f"{name}.c").write_text(source)
        manifest["harnesses"][name] = {"recipe": recipe, "targets": targets}
        covered |= set(targets)

    manifest["gap_total"] = len(gap)
    manifest["gap_targeted"] = len(covered & gap)
    manifest["gap_targeted_names"] = sorted(covered & gap)
    (out_dir / "manifest.json").write_text(json.dumps(manifest, indent=1) + "\n")
    return manifest


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("lib")
    ap.add_argument("--api", type=Path)
    ap.add_argument("--gap", type=Path)
    ap.add_argument("--out", type=Path)
    a = ap.parse_args(argv)

    from gapharn.config import load_target

    t = load_target(a.lib)
    api = a.api or t.results_dir / "api.json"
    gap = a.gap or t.results_dir / "gap.json"
    out = a.out or SRC_ROOT / "harnesses" / a.lib
    if a.lib != "libarchive":
        print(f"[gen_rule] recipes are libarchive-specific; {a.lib} not supported yet", file=sys.stderr)
        return 2
    m = generate(a.lib, api, gap, out)
    print(f"[gen_rule] {len(m['harnesses'])} harnesses -> {out}")
    print(f"[gen_rule] targeting {m['gap_targeted']}/{m['gap_total']} gap functions")
    return 0


if __name__ == "__main__":
    sys.exit(main())
