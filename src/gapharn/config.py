"""Per-target configuration (targets/<lib>/config.yaml) and project paths.

Command-line use (for shell scripts):
    python -m gapharn.config <lib> <key>
prints a string value as-is and a list value one item per line.
The special keys `harnesses` and `harness_support_files` print resolved paths.
"""
from __future__ import annotations

import glob
import os
import sys
from dataclasses import dataclass, field
from pathlib import Path

import yaml

SRC_ROOT = Path(__file__).resolve().parent.parent
TARGETS_DIR = SRC_ROOT / "targets"
RESULTS_DIR = Path(os.environ.get("GAPHARN_RESULTS", SRC_ROOT / "results")).resolve()
# Builds are large and slow on a Windows-mounted drive (/mnt/c); point
# GAPHARN_WORK at a Linux-native directory (e.g. ~/gapharn-work) to avoid that.
WORK_DIR = Path(os.environ.get("GAPHARN_WORK", SRC_ROOT / "work")).resolve()


@dataclass
class Target:
    name: str
    repo: str
    ref: str
    headers: list[str]
    include_dirs: list[str] = field(default_factory=list)
    defines: list[str] = field(default_factory=list)
    # Where `headers` / `include_dirs` are resolved: "src" = the library checkout,
    # "build" = <build-cov>/include (needed when public headers are generated by the build).
    header_base: str = "src"
    static_lib: str = ""
    # Static libraries linked before static_lib (e.g. a C++ wrapper library).
    extra_static_libs: list[str] = field(default_factory=list)
    link_flags: list[str] = field(default_factory=list)
    harness_globs: list[str] = field(default_factory=list)
    # Globs (relative to the checkout) removed from harness_globs matches.
    harness_exclude: list[str] = field(default_factory=list)
    # Sources compiled and linked into every existing harness (shared fuzz helpers).
    harness_support: list[str] = field(default_factory=list)
    seed_globs: list[str] = field(default_factory=list)

    @property
    def work_dir(self) -> Path:
        return WORK_DIR / self.name

    @property
    def src_dir(self) -> Path:
        return self.work_dir / "src"

    @property
    def results_dir(self) -> Path:
        return RESULTS_DIR / self.name

    def build_dir(self, variant: str) -> Path:
        return self.work_dir / f"build-{variant}"

    @property
    def header_root(self) -> Path:
        if self.header_base == "build":
            return self.build_dir("cov") / "include"
        if self.header_base == "src":
            return self.src_dir
        raise SystemExit(f"{self.name}: header_base must be 'src' or 'build', not {self.header_base!r}")

    def header_paths(self) -> list[Path]:
        """Public headers; entries may be globs (e.g. libxml/*.h)."""
        return _expand(self.header_root, self.headers)

    def include_paths(self) -> list[Path]:
        # The build's include dir always comes last, so generated headers are found.
        return [self.header_root / d for d in self.include_dirs] + [self.build_dir("cov") / "include"]

    def harness_paths(self) -> list[Path]:
        """Existing (e.g. OSS-Fuzz) harness sources matched by harness_globs.

        Globs may use environment variables (e.g. $OSS_FUZZ/projects/x/*.cc);
        relative globs are resolved against the library checkout.
        """
        excluded = set(_expand(self.src_dir, self.harness_exclude))
        return [p for p in _expand(self.src_dir, self.harness_globs) if p not in excluded]

    def harness_support_paths(self) -> list[Path]:
        return _expand(self.src_dir, self.harness_support)


def _expand(base: Path, patterns: list[str]) -> list[Path]:
    """Expand env vars and globs; relative patterns are resolved against base."""
    found: list[Path] = []
    for pattern in patterns:
        pattern = os.path.expandvars(pattern)
        if "$" in pattern:  # unset variable: skip instead of matching garbage
            continue
        if not os.path.isabs(pattern):
            pattern = str(base / pattern)
        found.extend(Path(p) for p in sorted(glob.glob(pattern)))
    return list(dict.fromkeys(found))


def load_target(name: str) -> Target:
    path = TARGETS_DIR / name / "config.yaml"
    if not path.is_file():
        raise SystemExit(f"no target config: {path}")
    data = yaml.safe_load(path.read_text()) or {}
    data.setdefault("name", name)
    unknown = set(data) - set(Target.__dataclass_fields__)
    if unknown:
        raise SystemExit(f"{path}: unknown keys {sorted(unknown)}")
    return Target(**data)


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print("usage: python -m gapharn.config <lib> <key>", file=sys.stderr)
        return 2
    target = load_target(argv[0])
    key = argv[1]
    if key == "harnesses":
        value = [str(p) for p in target.harness_paths()]
    elif key == "harness_support_files":
        value = [str(p) for p in target.harness_support_paths()]
    elif key in ("src_dir", "work_dir", "results_dir"):
        value = str(getattr(target, key))
    elif key in Target.__dataclass_fields__:
        value = getattr(target, key)
    else:
        print(f"unknown key: {key}", file=sys.stderr)
        return 2
    print("\n".join(value) if isinstance(value, list) else value)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
