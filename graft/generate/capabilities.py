"""What each engine can actually do, measured rather than assumed.

``configs/capabilities.yaml`` is generated by probing the real binaries (see
:func:`probe_engine` and ``python -m graft.generate.capabilities --probe``), because
guessing here would quietly poison every variant the mutator produces. Three
findings from the first probe run show why it has to be measured:

* **SQLite and Turso accept every type name.** ``CAST(NULL AS VARIANT)``
  succeeds on both, since SQLite resolves an unknown type name to an affinity
  rather than rejecting it. Acceptance therefore proves nothing; the probe
  records what ``typeof()`` / ``arrow_typeof()`` actually *reports*, and only a
  type the engine reports distinctly counts as supported.
* **Special float values are not portable.** ``CAST('NaN' AS DOUBLE)`` gives
  NaN on DuckDB, NULL on DataFusion and 0.0 on SQLite and Turso. A boundary
  mutation that emits NaN at a target that silently turns it into 0.0 is not
  the test it looks like, so ``values`` records whether the value survives.
* **A column alias on a derived table is not universal.** ``(VALUES (1)) AS
  v(a)`` and ``(SELECT 1) AS t(a)`` are rejected by SQLite and Turso, so the
  subquery-wrapping mutation has to avoid them for those targets.

Capability keys use the SPEC feature-tag vocabulary where one applies, so the
mutator, the signature and the generator share names.
"""

