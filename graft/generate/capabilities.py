#: the function that reports a value's type, per engine
TYPEOF_FUNCTION = {
    "duckdb": "typeof",
    "turso": "typeof",
    "sqlite": "typeof",
    "datafusion": "arrow_typeof",
}


@dataclass(frozen=True)
class TypeSupport:
    """One type at one engine."""

    label: str
    declared: str
    reported: str
    #: True for the one canonical label per reported type. False for an alias,
    #: where declaring DATE on SQLite really stores an integer, so swapping to
    #: it would be a silent no-op rather than a type mutation.
    distinct: bool
    #: the canonical label this one collapses onto, when it is an alias
    alias_of: str | None = None

    @property
    def usable(self) -> bool:
        """True if the mutator may emit this type at this engine."""
        return self.distinct


@dataclass(frozen=True)
class ValueSupport:
    """One special value at one engine."""

    label: str
    expression: str
    accepted: bool
    #: True when the value survives a round trip. DataFusion turns NaN into
    #: NULL and SQLite turns it into 0.0; neither "supports" NaN in the sense a
    #: boundary test needs.
    preserved: bool

    @property
    def usable(self) -> bool:
        """True if the mutator may emit this value at this engine."""
        return self.accepted and self.preserved


@dataclass
class EngineCapabilities:
    """Everything measured about one engine."""

    name: str
    dialect: str = ""
    engine_version: str = "UNKNOWN"
    engine_commit: str = "UNKNOWN"
    probed_at: str = "UNKNOWN"
    types: dict[str, TypeSupport] = field(default_factory=dict)
    values: dict[str, ValueSupport] = field(default_factory=dict)
    features: frozenset[str] = frozenset()
    functions: frozenset[str] = frozenset()

    # --- queries the mutator asks -------------------------------------------

    def has_feature(self, feature: str) -> bool:
        """True if the engine accepted this feature probe."""
        return feature in self.features

    def has_function(self, tag: str) -> bool:
        """True if the engine has this function; ``tag`` is ``fn:``/``agg:``/``win:``."""
        return tag in self.functions

    def usable_types(self) -> list[str]:
        """Type labels the mutator may emit, in config order."""
        return [label for label, support in self.types.items() if support.usable]

    def usable_values(self) -> list[str]:
        """Special-value labels the mutator may emit, in config order."""
        return [label for label, support in self.values.items() if support.usable]

    def declared_type(self, label: str) -> str | None:
        """Return the SQL type name to write for ``label``, or None if unusable."""
        support = self.types.get(label)
        return support.declared if support and support.usable else None

    def value_expression(self, label: str) -> str | None:
        """Return the SQL expression for a special value, or None if unusable."""
        support = self.values.get(label)
        return support.expression if support and support.usable else None


def _type_from_dict(label: str, raw: Mapping[str, Any]) -> TypeSupport:
    return TypeSupport(
        label=label,
        declared=str(raw["declared"]),
        reported=str(raw.get("reported", "UNKNOWN")),
        distinct=bool(raw.get("distinct", False)),
        alias_of=(str(raw["alias_of"]) if raw.get("alias_of") else None),
    )


def _value_from_dict(label: str, raw: Mapping[str, Any]) -> ValueSupport:
    return ValueSupport(
        label=label,
        expression=str(raw["expression"]),
        accepted=bool(raw.get("accepted", False)),
        preserved=bool(raw.get("preserved", False)),
    )


def load_capabilities(
    path: str | Path | None = None,
) -> dict[str, EngineCapabilities]:
    """Load ``configs/capabilities.yaml``.

    Returns:
        Engine name to :class:`EngineCapabilities`.

    Raises:
        FileNotFoundError: if the file is missing.
        ValueError: if an engine entry is malformed.
    """
    target = Path(path) if path is not None else config_dir() / "capabilities.yaml"
    doc = load_yaml(target)
    raw = (doc or {}).get("capabilities") or {}
    if not isinstance(raw, dict):
        raise ValueError(f"{target}: 'capabilities' must be a mapping")

    out: dict[str, EngineCapabilities] = {}
    for name, entry in raw.items():
        if not isinstance(entry, dict):
            raise ValueError(f"{target}: capabilities.{name} must be a mapping")
        out[name] = EngineCapabilities(
            name=name,
            dialect=str(entry.get("dialect", "")),
            engine_version=str(entry.get("engine_version", "UNKNOWN")),
            engine_commit=str(entry.get("engine_commit", "UNKNOWN")),
            probed_at=str(entry.get("probed_at", "UNKNOWN")),
            types={
                label: _type_from_dict(label, value)
                for label, value in (entry.get("types") or {}).items()
            },
            values={
                label: _value_from_dict(label, value)
                for label, value in (entry.get("values") or {}).items()
            },
            features=frozenset(entry.get("features") or ()),
            functions=frozenset(entry.get("functions") or ()),
        )
    return out


def get_capabilities(
    name: str, path: str | Path | None = None
) -> EngineCapabilities:
    """Load one engine's capabilities.

    Raises:
        KeyError: if the engine has not been probed.
    """
    table = load_capabilities(path)
    try:
        return table[name]
    except KeyError:
        raise KeyError(
            f"no probed capabilities for {name!r}; have {sorted(table)}. "
            "Run: python -m graft.generate.capabilities --probe"
        ) from None


# --- probing ----------------------------------------------------------------


def probe_engine(engine: Any, dialect: str = "") -> dict[str, Any]:
    """Probe one started engine and return a capabilities entry.

    Runs every probe table in this module against the real binary: type names
    (recording what the engine *reports*, not merely that it accepted the
    name), special values (recording whether they survive), clause features,
    and scalar/aggregate/window functions.

    Args:
        engine: a started :class:`adapters.base.Engine`.
        dialect: the dialect name from configs/targets.yaml.

    Returns:
        A JSON-ready dict in the shape ``configs/capabilities.yaml`` expects.
    """
    typeof = TYPEOF_FUNCTION.get(engine.name, "typeof")

    types: dict[str, dict[str, Any]] = {}
    for label, declared, literal in PROBE_TYPES:
        result = engine.run_case([], f"SELECT {typeof}(CAST({literal} AS {declared}))")
        reported = (
            str(result.rows[0][0])
            if result.ok and result.rows and result.rows[0]
            else "ERR"
        )
        types[label] = {"declared": declared, "reported": reported}
    resolve_type_aliases(types)

    values: dict[str, dict[str, Any]] = {}
    for label, expression in PROBE_VALUES:
        result = engine.run_case([], f"SELECT {expression}")
        accepted = result.ok
        preserved = accepted and _value_preserved(label, result)
        values[label] = {
            "expression": expression,
            "accepted": accepted,
            "preserved": preserved,
        }

    probed = {
        name
        for name, probe in FEATURE_PROBES.items()
        if engine.run_case([], probe).ok
    }
    # Each DDL probe needs its own fresh database: a successful CREATE INDEX
    # would otherwise still be there when the next probe runs, and a name
    # collision would be read as the engine refusing the feature.
    for name, probe in DDL_PROBES.items():
        if engine.run_case(list(PROBE_TABLE), probe).ok:
            probed.add(name)
    for name, probe in ALTER_PROBES.items():
        if engine.run_case(list(PROBE_TABLE), probe).ok:
            probed.add(name)
    for name, probe in CONSTRAINT_PROBES.items():
        if engine.run_case([], probe).ok:
            probed.add(name)
    features = sorted(probed)

    functions: list[str] = []
    for tag, expression in SCALAR_PROBES.items():
        if engine.run_case([], f"SELECT {expression}").ok:
            functions.append(tag)
    for table in (AGGREGATE_PROBES, WINDOW_PROBES):
        for tag, expression in table.items():
            renamed = expression.replace("(a", "(probe_t.a").replace(" a)", " probe_t.a)")
            query = f"SELECT {expression} FROM probe_t"
            if engine.run_case(list(PROBE_TABLE), query).ok:
                functions.append(tag)

    return {
        "dialect": dialect,
        "engine_version": engine.version(),
        "engine_commit": engine.commit(),
        "types": types,
        "values": values,
        "features": features,
        "functions": sorted(functions),
    }


def resolve_type_aliases(types: dict[str, dict[str, Any]]) -> None:
    """Mark one canonical label per reported type and alias the rest, in place.

    Several declared types can collapse onto one real type. On DuckDB REAL and
    FLOAT both report FLOAT; on SQLite and Turso everything from TINYINT to
    JSON reports ``integer``, which is affinity aliasing rather than support.
    Exactly one label per reported type is marked ``distinct`` - preferring the
    label whose own name matches what the engine reported - and the others get
    ``alias_of`` pointing at it. The mutator only emits distinct types, so it
    never produces a swap that is silently a no-op.
    """
    groups: dict[str, list[str]] = {}
    for label, entry in types.items():
        if entry["reported"] != "ERR":
            groups.setdefault(entry["reported"], []).append(label)

    canonical: dict[str, str] = {}
    for reported, labels in groups.items():
        simple = reported.split("(")[0].strip().lower()
        match = next((l for l in labels if l == simple), None)
        canonical[reported] = match or labels[0]

    for label, entry in types.items():
        reported = entry["reported"]
        if reported == "ERR":
            entry["distinct"] = False
            continue
        chosen = canonical[reported]
        entry["distinct"] = label == chosen
        if label != chosen:
            entry["alias_of"] = chosen


def _value_preserved(label: str, result: Any) -> bool:
    """True if a probed special value came back as itself.

    Text-protocol engines return strings, so the check is on the rendered form.
    """
    if not result.rows or not result.rows[0]:
        return False
    cell = result.rows[0][0]
    if cell is None:
        return False  # DataFusion turns NaN into NULL
    text = str(cell).strip().lower()
    if label == "nan":
        return "nan" in text
    if label == "infinity":
        return "inf" in text and not text.startswith("-")
    if label == "neg_infinity":
        return "inf" in text and text.startswith("-")
    if label == "negative_zero":
        return text.startswith("-")
    if label == "int64_min":
        return text == "-9223372036854775808"
    if label == "int64_max":
        return text == "9223372036854775807"
    if label == "empty_string":
        return text == ""
    if label == "long_string":
        return len(str(cell)) == 1000
    if label == "unicode_string":
        return "中" in str(cell)
    return True


def _write_probed(out: Path | None = None) -> int:
    """Probe every configured engine and write ``configs/capabilities.yaml``.

    Slow (it runs a few hundred one-statement queries per engine), so it is a
    deliberate command rather than something any import triggers.
    """
    import time

    from graft.engines import create_engine
    from graft.config import load_targets

    probed_at = time.strftime("%Y-%m-%d", time.gmtime())
    entries: dict[str, Any] = {}
    for name, target in load_targets().items():
        engine = create_engine(name, target.kind, target=target)
        try:
            entry = probe_engine(engine, dialect=target.dialect)
        finally:
            engine.close()
        entry["probed_at"] = probed_at
        entries[name] = entry
        print(
            f"{name:11} types={sum(1 for t in entry['types'].values() if t['distinct'])}"
            f"/{len(entry['types'])} "
            f"values={sum(1 for v in entry['values'].values() if v['preserved'])}"
            f"/{len(entry['values'])} "
            f"features={len(entry['features'])} functions={len(entry['functions'])}",
            flush=True,
        )

    header = (
        "# configs/capabilities.yaml - what each engine can actually do.\n"
        "#\n"
        "# GENERATED by `python -m graft.generate.capabilities --probe` on "
        f"{probed_at}; do not hand-edit.\n"
        "# Every entry is measured against the real binary named in\n"
        "# configs/targets.yaml, because acceptance alone is misleading: SQLite\n"
        "# and Turso accept any type name and resolve it to an affinity, so\n"
        "# `types.*.reported` (what typeof()/arrow_typeof() says) decides, and\n"
        "# `types.*.distinct` is false for an affinity alias. `values.*.preserved`\n"
        "# is false where a value does not survive a round trip - NaN becomes\n"
        "# NULL on DataFusion and 0.0 on SQLite and Turso.\n"
    )
    target_path = out or (config_dir() / "capabilities.yaml")
    target_path.write_text(
        header + yaml.safe_dump({"capabilities": entries}, sort_keys=False),
        encoding="utf-8",
    )
    print(f"wrote {target_path}")
    return 0


def main(argv: Sequence[str] | None = None) -> int:
    """Print a capability summary, or re-probe the engines with ``--probe``."""
    parser = argparse.ArgumentParser(description="engine capabilities")
    parser.add_argument("--probe", action="store_true", help="re-probe every engine")
    parser.add_argument("--out", help="where to write the probed YAML")
    args = parser.parse_args(argv)

    if args.probe:
        return _write_probed(Path(args.out) if args.out else None)

    table = load_capabilities()
    for name, caps in table.items():
        print(
            f"{name:11} dialect={caps.dialect:10} types={len(caps.usable_types()):3} "
            f"values={len(caps.usable_values()):2} features={len(caps.features):3} "
            f"functions={len(caps.functions):3} version={caps.engine_version}"
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
